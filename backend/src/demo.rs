pub fn demo_payload() -> DemoPayload {
    let lists = demo_playlists();
    let personal = build_personal_demo(lists[0].clone());
    let comparison = compare_playlists(&lists[0], &lists[1]);
    let epoch = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_secs();
    DemoPayload {
        generated_at: format!("unix:{epoch}"),
        disclosure: "本页音乐元数据、推荐和匹配为内置离线 Demo；没有读取或修改任何真实音乐账号。"
            .into(),
        personal,
        comparison,
        available_playlists: lists,
    }
}
