fn track(
    id: &str,
    title: &str,
    artist: &str,
    album: &str,
    genres: &[&str],
    year: u16,
    language: &str,
    energy: f32,
    mood: &[&str],
) -> Track {
    Track {
        id: id.into(),
        title: title.into(),
        normalized_title: normalize_text(title),
        artists: vec![artist.into()],
        album: Some(album.into()),
        genres: normalize_genres(genres.iter()),
        release_year: Some(year),
        language: Some(language.into()),
        duration_ms: Some(220_000),
        platform: "demo".into(),
        platform_url: Some(format!(
            "https://open.spotify.com/search/{}",
            urlencoding::encode(&format!("{artist} {title}"))
        )),
        external_ids: HashMap::new(),
        version_type: VersionType::Original,
        mood_tags: mood.iter().map(|v| (*v).into()).collect(),
        energy_score: Some(energy),
        popularity: Some(0.55),
        metadata_confidence: 0.88,
    }
}

